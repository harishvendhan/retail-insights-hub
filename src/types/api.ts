/* ---------- import ---------- */

export interface ImportColumnMapping {
  sourceColumn: string;
  targetField: string | null;
  ambiguous: boolean;
  options?: string[];
}

export interface ImportInvalidRow {
  rowNumber: number;
  reason: string;
  values: Record<string, string>;
}

export interface ImportUploadResponse {
  importId: string;
  fileName: string;
  totalRows: number;
  validRows: number;
  invalidRows: number;
  columnMappings: ImportColumnMapping[];
  invalidRowDetails: ImportInvalidRow[];
  preview: Record<string, string>[];
}

export interface ImportConfirmResponse {
  importId: string;
  status: "completed" | "partial" | "failed";
  inserted: number;
  updated: number;
  skipped: number;
  message: string;
}

export interface ImportHistoryEntry {
  importId: string;
  fileName: string;
  uploadedAt: string;
  status: "completed" | "partial" | "failed" | "pending";
  totalRows: number;
  validRows: number;
  invalidRows: number;
}

/* ---------- AI chat / voice ---------- */

export interface DataReferenceTable {
  columns: string[];
  rows: (string | number)[][];
}

export interface DataReference {
  /** Which backend tool/dataset grounded the answer. */
  source: string;
  context: string;
  table?: DataReferenceTable;
  values?: { label: string; value: string }[];
}

export interface ClarificationOption {
  label: string;
  value: string;
}

export interface AiAnswer {
  conversationId: string;
  messageId: string;
  /** Natural-language answer in the language the backend chose. Rendered as-is. */
  answer: string;
  language: Language;
  status: "answered" | "insufficient_data" | "needs_clarification";
  isEstimate?: boolean;
  dataReferences?: DataReference[];
  clarificationOptions?: ClarificationOption[];
}

export interface AiQueryRequest {
  question: string;
  language: Language;
  conversationId?: string;
}

export interface VoiceQueryResponse extends AiAnswer {
  transcript: string;
  detectedLanguage: Language;
  /** Backend-generated TTS audio URL, if any. */
  audioUrl?: string | null;
}

export interface ChatMessage {
  id: string;
  role: "user" | "assistant";
  content: string;
  language?: Language;
  createdAt: string;
  status?: AiAnswer["status"];
  isEstimate?: boolean;
  dataReferences?: DataReference[];
  clarificationOptions?: ClarificationOption[];
}

export interface Conversation {
  conversationId: string;
  messages: ChatMessage[];
}

/* ---------- reports ---------- */

export type ReportType =
  | "sales"
  | "inventory"
  | "low-stock"
  | "reorder"
  | "expiry"
  | "product-performance"
  | "category-performance"
  | "supplier-performance";

export interface ReportDefinition {
  type: ReportType;
  title: string;
  description: string;
  formats: ("pdf" | "excel" | "csv")[];
}

export interface ReportPreview {
  type: ReportType;
  title: string;
  context: string;
  columns: string[];
  rows: (string | number)[][];
  downloadUrl: string;
}
